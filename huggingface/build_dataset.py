def build(output_dir: Path) -> None:
    source_sha = _source_sha()
    if output_dir.exists():
        shutil.rmtree(output_dir)
    data_dir = output_dir / "data"
    data_dir.mkdir(parents=True)

    core_results = [
        run_synthetic_experiment(
            rows=CORE_ROWS,
            seed=SEED,
            model_name=model,
            bootstrap_replicates=BOOTSTRAP_REPLICATES,
            write_run=False,
        )
        for model in ("logistic", "vfl-hist-gbdt")
    ]
    core = pd.DataFrame([_core_row(result, source_sha) for result in core_results])
    core.to_parquet(data_dir / "core_model_comparison.parquet", index=False)

    with tempfile.TemporaryDirectory(prefix="vertimosaic-hf-") as temp:
        temp_dir = Path(temp)
        ablation = run_ablation_study(
            rows=STUDY_ROWS,
            seed=SEED,
            model_name="logistic",
            output=temp_dir / "party_ablation.csv",
            write_run=False,
        )
        _decorate(ablation, "party_ablation", source_sha).to_parquet(
            data_dir / "party_ablation.parquet", index=False
        )

        overlap = run_overlap_study(
            rows=STUDY_ROWS,
            seed=SEED,
            model_name="logistic",
            output=temp_dir / "partial_overlap.csv",
            write_run=False,
        )
        _decorate(overlap, "partial_overlap", source_sha).to_parquet(
            data_dir / "partial_overlap.parquet", index=False
        )

        dropout = run_dropout_study(
            rows=STUDY_ROWS,
            seed=SEED,
            max_iter=250,
            output=temp_dir / "party_dropout.csv",
            write_run=False,
        )
        _decorate(dropout, "party_dropout", source_sha).to_parquet(
            data_dir / "party_dropout.parquet", index=False
        )

        drift = run_drift_study(
            rows=STUDY_ROWS,
            seed=SEED,
            output=temp_dir / "feature_drift.csv",
            write_run=False,
        )
        _decorate(drift, "feature_drift", source_sha).to_parquet(
            data_dir / "feature_drift.parquet", index=False
        )

    manifest = {
        "dataset_id": DATASET_ID,
        "schema_version": "1.0",
        "generated_at_utc": datetime.now(UTC).isoformat(),
        "source_commit": source_sha,
        "seed": SEED,
        "core_rows": CORE_ROWS,
        "study_rows": STUDY_ROWS,
        "bootstrap_replicates": BOOTSTRAP_REPLICATES,
        "configurations": {
            "core-model-comparison": len(core),
            "party-ablation": len(ablation),
            "partial-overlap": len(overlap),
            "party-dropout": len(dropout),
            "feature-drift": len(drift),
        },
        "external_source_rows_included": False,
        "ieee_cis_rows_included": False,
        "raw_feature_tables_pooled": False,
        "privacy_claim": "research raw-feature locality; no cryptographic privacy guarantee",
    }
    _write_json(output_dir / "summaries" / "manifest.json", manifest)
    _write_json(
        output_dir / "provenance" / "source_data_policy.json",
        {
            "external_source_rows_included": False,
            "policy": (
                "Third-party source datasets are not redistributed by this Hugging Face dataset. "
                "Source-specific licensing remains separate from VertiMosaic's Apache-2.0 code "
                "and generated benchmark artifacts."
            ),
            "source_policy_document": (
                "https://github.com/sauravsingla/VertiMosaic/blob/main/DATA_LICENSES.md"
            ),
            "ieee_cis": "authorized local inputs only; never redistributed",
        },
    )
    (output_dir / "README.md").write_text(_dataset_card(), encoding="utf-8")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Build the VertiMosaic Hugging Face dataset")
    parser.add_argument("--output", type=Path, default=Path("hf-dataset"))
    args = parser.parse_args()
    build(args.output)
