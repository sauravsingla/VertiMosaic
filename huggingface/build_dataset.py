from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import tempfile
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import pandas as pd

from vertimosaic.experiments import (
    run_ablation_study,
    run_drift_study,
    run_dropout_study,
    run_overlap_study,
    run_synthetic_experiment,
)

DATASET_ID = "sauravsingla08/VertiMosaic-VFL-Benchmark"
SEED = 42
CORE_ROWS = 2000
STUDY_ROWS = 1200
BOOTSTRAP_REPLICATES = 200


def _source_sha() -> str:
    configured = os.environ.get("GITHUB_SHA") or os.environ.get("SOURCE_SHA")
    if configured:
        return configured
    try:
        return subprocess.check_output(
            ["git", "rev-parse", "HEAD"], text=True, stderr=subprocess.DEVNULL
        ).strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def _write_json(path: Path, payload: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def _core_row(result: dict[str, Any], source_sha: str) -> dict[str, Any]:
    metrics = result["metrics"]
    communication = result["communication"]
    return {
        "benchmark_family": "core_model_comparison",
        "mode": result["mode"],
        "model": result["model"],
        "rows": result["rows"],
        "seed": result["seed"],
        "bootstrap_replicates": result["bootstrap_replicates"],
        "roc_auc": metrics.get("roc_auc"),
        "pr_auc": metrics.get("pr_auc"),
        "f1": metrics.get("f1"),
        "log_loss": metrics.get("log_loss"),
        "brier": metrics.get("brier"),
        "ece": metrics.get("ece"),
        "threshold": result.get("threshold"),
        "training_steps": result.get("training_steps"),
        "training_seconds": result.get("training_seconds"),
        "inference_seconds": result.get("inference_seconds"),
        "peak_rss_bytes": result.get("peak_rss_bytes"),
        "estimated_communication_bytes": result.get("estimated_communication_bytes"),
        "communication_message_count": communication.get("message_count"),
        "communication_scalar_count": communication.get("scalar_count"),
        "forward_communication_bytes": communication.get("forward_estimated_bytes"),
        "backward_communication_bytes": communication.get("backward_estimated_bytes"),
        "traffic_type": communication.get("traffic_type"),
        "raw_features_pooled": False,
        "source_type": "fully_synthetic",
        "source_commit": source_sha,
    }


def _decorate(frame: pd.DataFrame, family: str, source_sha: str) -> pd.DataFrame:
    result = frame.copy()
    result.insert(0, "benchmark_family", family)
    result["seed"] = SEED
    result["rows"] = STUDY_ROWS
    result["raw_features_pooled"] = False
    result["source_type"] = "fully_synthetic"
    result["source_commit"] = source_sha
    return result


