    evaluation = _load_json(root / "evaluation.json")
    by_name = {str(row.get("model")): row for row in evaluation}
    logistic = by_name.get("vfl_logistic", {})
    gbdt = by_name.get("vfl_hist_gbdt", {})
    source_commit = str(metadata.get("source_commit", "unknown"))
    benchmark = metadata.get("benchmark", {})
    rows = benchmark.get("rows", 800)
    seed = benchmark.get("seed", 42)
    train_rows = benchmark.get("train_rows", 560)
    validation_rows = benchmark.get("validation_rows", 120)
    test_rows = benchmark.get("test_rows", 120)

