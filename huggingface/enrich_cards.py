def main() -> None:
    parser = argparse.ArgumentParser(description="Render polished Hugging Face cards")
    subparsers = parser.add_subparsers(dest="kind", required=True)

    dataset_parser = subparsers.add_parser("dataset")
    dataset_parser.add_argument("--root", type=Path, default=Path("hf-dataset"))

    model_parser = subparsers.add_parser("model")
    model_parser.add_argument("--root", type=Path, default=Path("hf-model"))

    args = parser.parse_args()
    root: Path = args.root
    card = _dataset_card(root) if args.kind == "dataset" else _model_card(root)
    (root / "README.md").write_text(card, encoding="utf-8")


if __name__ == "__main__":
    main()
