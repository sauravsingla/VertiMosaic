def _load_json(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8"))


def _fmt_metric(record: dict[str, Any], key: str) -> str:
    value = record.get("test_metrics", {}).get(key)
    return f"{float(value):.4f}" if isinstance(value, (int, float)) else "—"


def _dataset_card(root: Path) -> str:
    manifest = _load_json(root / "summaries" / "manifest.json")
    source_commit = str(manifest.get("source_commit", "unknown"))
    generated_at = str(manifest.get("generated_at_utc", "unknown"))
    core_rows = manifest.get("core_rows", 2000)
    study_rows = manifest.get("study_rows", 1200)
    seed = manifest.get("seed", 42)
    bootstrap = manifest.get("bootstrap_replicates", 200)

